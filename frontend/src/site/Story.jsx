const ACCENT = new THREE.Color("#ff8a3d");
const SCAN = new THREE.Color("#5ee1ff");

/** Demo organizer generated by the real backend, so the hero model is the real thing. */
function useDemoModel() {
  const [result, setResult] = useState(null);
  const [error, setError] = useState(null);
  useEffect(() => {
    let alive = true;
    (async () => {
      try {
        const res = await loadDemoModel();
        if (alive) setResult(res);
      } catch (e) {
        if (alive) setError(e.message);
      }
    })();
    return () => {
      alive = false;
    };
  }, []);
  return { result, error };
}

function StoryScene({ result, geometry, progressRef, readoutRef }) {
  const group = useRef();
  const solidMat = useRef();
  const wireMat = useRef();
  const scanBar = useRef();
  const pocketRefs = useRef([]);
  const clip = useMemo(() => new THREE.Plane(new THREE.Vector3(0, -1, 0), 1000), []);
  const [w, d, h] = result.size_mm;
  const reduced = prefersReducedMotion();

  useFrame((state, dt) => {
    const p = progressRef.current;
    const chapter = Math.min(3, Math.floor(p * 4));
    const local = p * 4 - chapter; // 0..1 inside the chapter

    // Spin with scroll (plus a slow idle drift so it never looks frozen).
    const target = -0.6 + p * Math.PI * 2.2 + (reduced ? 0 : state.clock.elapsedTime * 0.05);
    group.current.rotation.y += (target - group.current.rotation.y) * Math.min(1, dt * 6);

    // C2 SCAN: x-ray wireframe + sweeping scan bar.
    const scanning = chapter === 1;
    wireMat.current.opacity += ((scanning ? 0.85 : 0) - wireMat.current.opacity) * Math.min(1, dt * 8);
    solidMat.current.opacity += ((scanning ? 0.12 : 1) - solidMat.current.opacity) * Math.min(1, dt * 8);
    solidMat.current.transparent = solidMat.current.opacity < 0.99;
    scanBar.current.visible = scanning;
    scanBar.current.position.x = -w / 2 + ((local * 1.6) % 1) * w;

    // C3 FORGE: pockets light up one after another.
    const n = pocketRefs.current.length;
    pocketRefs.current.forEach((m, i) => {
      if (!m) return;
      const on = chapter === 2 && local > i / Math.max(n, 1) * 0.85;
      m.material.opacity += ((on ? 0.55 : 0) - m.material.opacity) * Math.min(1, dt * 10);
      m.visible = m.material.opacity > 0.01;
    });

    // C4 PRINT: layer-by-layer reveal with a clipping plane.
    const layerH = chapter === 3 ? Math.max(0.6, Math.min(1, local * 1.3)) * h : h + 50;
    clip.constant += (layerH - clip.constant) * Math.min(1, dt * 8);

    if (readoutRef.current) {
      const deg = ((group.current.rotation.y * 180) / Math.PI) % 360;
      const layer = chapter === 3 ? Math.min(h, clip.constant).toFixed(1) : h.toFixed(1);
      readoutRef.current.textContent =
        `ROT ${deg >= 0 ? "+" : ""}${deg.toFixed(1)}°   Z ${layer} MM   ● ${CHAPTERS[chapter].mode}`;
    }
  });

  return (
    <group ref={group}>
      <group rotation={[-Math.PI / 2, 0, 0]} position={[-w / 2, 0, d / 2]}>
        <mesh geometry={geometry} castShadow>
          <meshStandardMaterial ref={solidMat} color={ACCENT} roughness={0.5} metalness={0.05} clippingPlanes={[clip]} clipShadows side={THREE.DoubleSide} />
        </mesh>
        <mesh geometry={geometry}>
          <meshBasicMaterial ref={wireMat} color={SCAN} wireframe transparent opacity={0} depthWrite={false} />
        </mesh>
        {result.pockets.map((pk, i) => (
          <mesh
            key={pk.id}
            ref={(m) => (pocketRefs.current[i] = m)}
            position={[pk.x + pk.w / 2, pk.y + pk.d / 2, 2 + pk.wall_h / 2]}
            visible={false}
          >
            <boxGeometry args={[pk.w, pk.d, pk.wall_h]} />
            <meshBasicMaterial color={SCAN} transparent opacity={0} depthWrite={false} />
          </mesh>
        ))}
      </group>
      <mesh ref={scanBar} position={[0, h / 2, 0]} visible={false}>
        <boxGeometry args={[1.2, h * 2.2, d * 1.3]} />
        <meshBasicMaterial color={SCAN} transparent opacity={0.35} depthWrite={false} />
      </mesh>
    </group>
  );
}

function ChapterText({ chapter, index, active }) {
  const tag = useScramble(`[ ${chapter.tag} ]`, active, 500);
  return (
    <article className={`chapter ${active ? "active" : ""}`} aria-hidden={!active}>
      <div className="chapter-tag mono">
        <span>{tag}</span>
        <span className="dots">· · ·· ··· ·</span>
        <span>0{index + 1} / 04</span>
      </div>
      <h2>
        {chapter.title.map((line) => (
          <span key={line}>{line}</span>
        ))}
      </h2>
      <p>{chapter.body}</p>
    </article>
  );
}

export default function Story() {
  const sectionRef = useRef(null);
  const readoutRef = useRef(null);
  const progressRef = useSectionProgressRef(sectionRef);
  const [chapter, setChapter] = useState(0);
  const { result, error } = useDemoModel();
  const { geometry } = useStlGeometry(result?.stl_url);

  // Only re-render React when the chapter changes, not on every scroll pixel.
  useEffect(() => {
    let raf;
    const loop = () => {
      const c = Math.min(3, Math.floor(progressRef.current * 4));
      setChapter((prev) => (prev === c ? prev : c));
      raf = requestAnimationFrame(loop);
    };
    raf = requestAnimationFrame(loop);
    return () => cancelAnimationFrame(raf);
  }, [progressRef]);

  const span = result ? Math.max(result.size_mm[0], result.size_mm[1]) : 240;

  return (
    <section className="story" id="story" ref={sectionRef}>
      <div className="story-sticky">
        <div className="story-copy">
          <div className="section-label mono">[ 01 / HOW IT WORKS ]</div>
          <div className="chapters">
            {CHAPTERS.map((c, i) => (
              <ChapterText key={c.tag} chapter={c} index={i} active={i === chapter} />
            ))}
          </div>
          <div className="chapter-dots" aria-hidden>
            {CHAPTERS.map((c, i) => (
              <span key={c.tag} className={i === chapter ? "on" : i < chapter ? "done" : ""} />
            ))}
          </div>
        </div>

        <div className="story-stage">
          <div className="stage-frame mono">
            <span>FIG. {chapter + 1}: {CHAPTERS[chapter].mode}</span>
            <span>{result ? `${result.size_mm[0]} × ${result.size_mm[1]} × ${result.size_mm[2]} MM` : "LOADING MODEL…"}</span>
          </div>
          <ErrorBoundary fallback={() => <div className="stage-fallback">3D preview unavailable in this browser.</div>}>
            {geometry && result ? (
              <Canvas
                shadows
                dpr={[1, 2]}
                camera={{ position: [span * 1.05, span * 1.0, span * 1.25], fov: 35, near: 1, far: 5000 }}
                onCreated={({ gl }) => (gl.localClippingEnabled = true)}
              >
                <hemisphereLight args={["#dfe8ff", "#2a2118", 0.9]} />
                <directionalLight position={[150, 300, 120]} intensity={1.7} castShadow />
                <directionalLight position={[-200, 120, -150]} intensity={0.5} />
                <StoryScene result={result} geometry={geometry} progressRef={progressRef} readoutRef={readoutRef} />
                <gridHelper args={[600, 60, "#3a3326", "#221f1a"]} position={[0, -0.5, 0]} />
              </Canvas>
            ) : (
              <div className="stage-fallback mono">
                {error ? `Start the DeskForge server to see the live model (${error})` : "Compiling demo organizer…"}
              </div>
            )}
          </ErrorBoundary>
          <div className="stage-readout mono" ref={readoutRef}>ROT +0.0°   Z 0.0 MM   ● LOCK</div>
          <div className="stage-note mono">SCROLL TO SPIN · LIVE CADQUERY OUTPUT, NOT A RENDER</div>
        </div>
      </div>
    </section>
  );
}
